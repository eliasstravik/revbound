import { definePlugin } from "revbound";

const P = "revbound/agent";
const SRC = "revbound/src/plugins/agent";
const HEAD = "// Generated by `revbound sync` from revbound.config.ts (the agent plugin); do not edit.";

/** The chat apps the agent can be reached from, each an eve channel on the one agent. */
export const CHANNELS = ["console", "slack", "teams"] as const;
export type Channel = (typeof CHANNELS)[number];

/** Each channel's keys, as Connections shows them. */
export const CHANNEL_KEYS: Record<Exclude<Channel, "console">, { name: string; label: string }[]> = {
  slack: [
    { name: "SLACK_BOT_TOKEN", label: "Slack app's bot token (agent)" },
    { name: "SLACK_SIGNING_SECRET", label: "Slack app's signing secret (agent)" },
  ],
  teams: [
    { name: "MICROSOFT_APP_ID", label: "Teams bot's app id (agent)" },
    { name: "MICROSOFT_APP_PASSWORD", label: "Teams bot's app password (agent)" },
    { name: "MICROSOFT_TENANT_ID", label: "The company's Microsoft tenant id (agent)" },
  ],
};

export type AgentOptions = {
  /** Where people reach the agent; default ["console"]. Add one with `npx revbound agent add <channel>`. */
  channels?: Channel[];
  /** An AI Gateway model id for the chat; default by REVBOUND_AGENT_BACKEND (docs: agent). */
  model?: string;
};

const reexport = (module: string, name = "default") =>
  `${HEAD}\nexport { ${name === "default" ? "default" : `${name} as default`} } from ${JSON.stringify(`${P}/eve/${module}`)};\n`;

/** The eve agent folder (`agent/`) for these options: thin files that load the agent from this package. */
export function agentFiles(channels: readonly Channel[], model?: string): Record<string, string | { link: string }> {
  const files: Record<string, string | { link: string }> = {
    "agent/agent.ts": `${HEAD}\nimport { chatAgent } from "${P}/eve/agent";\n\nexport default chatAgent(${JSON.stringify(model ? { model } : {})});\n`,
    "agent/instructions.ts": reexport("instructions"),
    "agent/sandbox.ts": `${HEAD}\nexport { default, environment } from "${P}/eve/sandbox";\n`,
    "agent/channels/eve.ts": channels.includes("console") ? reexport("console") : reexport("closed"),
    "agent/tools/start_run.ts": reexport("tools", "startRun"),
    "agent/tools/run_status.ts": reexport("tools", "runStatus"),
    "agent/tools/git__gh.ts": reexport("tools", "ghTool"),
    "agent/tools/glob.ts": `${HEAD}\nexport { default } from "eve/tools/glob";\n`,
    "agent/tools/grep.ts": `${HEAD}\nexport { default } from "eve/tools/grep";\n`,
    "agent/extensions/git.ts": `${HEAD}\nimport git from "eve/extensions/git";\nimport { github } from "${P}/eve/git";\n\nconst config = github();\nexport default git(config ? { github: config } : {});\n`,
    // The company's skills, as eve skills.
    "agent/skills": { link: "../.agents/skills" },
  };
  if (channels.includes("slack")) files["agent/channels/slack.ts"] = reexport("slack");
  if (channels.includes("teams")) files["agent/channels/teams.ts"] = reexport("teams");
  return files;
}

/**
 * The agent: one eve agent in the company's own project that works on it like a teammate's coding agent, reached from
 * the console's Chat page and from chat apps (eve channels). It reads the project, changes workflows (local edits on a
 * laptop, pull requests when deployed) and starts runs through the ledger after the asker's own yes.
 */
export function agent(opts: AgentOptions = {}) {
  const channels = [...new Set<Channel>(opts.channels ?? ["console"])];
  for (const c of channels) if (!(CHANNELS as readonly string[]).includes(c)) throw new Error(`agent(): unknown channel ${JSON.stringify(c)}; use ${CHANNELS.join(", ")}.`);
  return definePlugin({
    name: "agent",
    api: 1,
    needs: ["workflows", "ledger"],
    files: agentFiles(channels, opts.model),
    views: channels.includes("console") ? [{ path: "chat", title: "Chat", nav: { label: "Chat", order: 5 }, fill: true, component: `${P}/view` }] : [],
    connections: channels.flatMap((c) => (c === "console" ? [] : CHANNEL_KEYS[c])),
    cli: [{ name: "agent", describe: "the agent's chat apps: `revbound agent add slack`, `remove`, `status`", run: `${P}/cli` }],
    dev: `${P}/dev`,
    next: `${P}/next`,
    checks: `${P}/checks`,
    options: { channels, ...(opts.model && { model: opts.model }) },
    agents: `- \`agent/\` is the project's chat agent (an eve agent), written by \`revbound sync\` from the agent plugin's options; never edit it.
  People reach it from the console's Chat page${channels.length > 1 ? ` and ${channels.filter((c) => c !== "console").join(", ")}` : ""}. Add a chat app with
  \`npx revbound agent add slack\` (docs: agent).`,
    docs: { agent: `${SRC}/docs/agent.md` },
  });
}
